/**
 * 匹配权重。调参不改查询代码，只改这里。
 *
 * 一条证据 = **路权重 × 相关度** × 时长 × 近因。前两项回答「这条证据有多能说明
 * 他真的做过用户要的那件事」：路权重管字段是谁写的，相关度管这段原文和查询词
 * 是不是一回事。
 */

import type { Route } from "#/db/schema";

export type { Route } from "#/db/schema";

/**
 * 六路证据的可信度。
 *
 * 序列与岗位是受控字段——HR 系统里为这一段登记的归属，一段一个值、可追溯，
 * 不是本人自述，所以最高。（在职段来自异动流程，入职前段来自工作经历表；
 * 两者都是登记字段，所以同档——强度只看字段来源，不看 kind。）
 *
 * 部门 / 公司同样受控且全员都有，但它描述的是团队的事，不是本人的事，故次之。
 *
 * 简历原文最低，四条叠加：提到不等于做过（"配合算法团队"会和算法相近，主语
 * 是别人）；本人自述、无校验；长文本上语义相似的假阳性高；上游文本可能缺失或
 * 被截断，相关度会受描述完整度影响——不可比。
 * 它只该用来在受控字段已经把人筛出来之后做加分，不该单独把人送进结果。
 *
 * 能力词与做过的事是模型从简历原文里读出来的短说法，**来源**没变，所以和
 * 简历原文同一档：强度只看字段来源，读法再好也不会让自述变成登记。它们比
 * 整段原文强的地方在相关度那一项——短说法上重排分得开主语和重点，「配合算法
 * 团队完成上线」抽出来是「模型上线」，不再和「负责算法」混在一起。
 * 给它们单开一档（比如 0.35）会撞上下面 TENURE_FLOOR 那条硬约束：
 * 0.25 / 0.35 > 0.56，时长就能翻盘档位。
 */
export const ROUTE_WEIGHTS: Record<Route, number> = {
	seq: 1.0,
	title: 1.0,
	org: 0.5,
	skill: 0.25,
	did: 0.25,
	description: 0.25,
};

/**
 * 路径判定顺序直接由权重推导：一段几路同时过阈值时，加权相关度最高的一路胜出；
 * 同权重时保留声明顺序——抽取的两路排在简历原文前面，同分时给用户看的是
 * 一条能读的短说法，而不是「简历原文」四个字。
 */
export const ROUTE_ORDER = (Object.keys(ROUTE_WEIGHTS) as Route[]).sort(
	(a, b) => ROUTE_WEIGHTS[b] - ROUTE_WEIGHTS[a],
);

export type Strength = "controlled" | "org" | "claimed";

/** 每一路对应的可解释证据强度；排名判定和界面编码共同使用这一份映射。 */
export const ROUTE_STRENGTH: Record<Route, Strength> = {
	seq: "controlled",
	title: "controlled",
	org: "org",
	skill: "claimed",
	did: "claimed",
	description: "claimed",
};

export function isControlledRoute(route: Route) {
	return ROUTE_STRENGTH[route] === "controlled";
}

/**
 * 命中判定分两步，两个模型各管一步（phrases.ts）：
 *
 * 1. **召回**：查询词嵌成向量，语料里余弦相似度过 `RECALL_MIN` 的说法都算候选，
 *    按相似度取前 `RECALL_MAX` 个。真实语料上不相关的短语落在 0.45 到 0.6，
 *    下限放在 0.5 是为了不漏，上限才是真正的闸。稠密向量在两三个字的短语上区分度很弱
 *    （真实语料上「前端开发」对「后端研发」和对「泛前端研发」都是 0.70，
 *    「团队管理」对「数据管理」0.74），所以这一步只负责**不漏**，下限放得低。
 * 2. **判定**：交叉编码器把查询词和每个候选放在一起读，给出相关度；过
 *    `RELEVANCE_MIN` 才算命中。它分得开一字之差的反义和同后缀的不同事
 *    （同一批例子上 0.81 对 0.23、0.995 对 0.02），所以这一步负责**不错**。
 *
 * `RELEVANCE_MIN` 是整套检索唯一的**成员资格**阈值：AND 判定、总人数、分面
 * 「点了还剩几人」全建立在「过没过这条线」上，所以它必须是一个全站常量，
 * 不能逐查询变。0.55 来自真实语料上的抽样：相关的说法在 0.65 以上，不相关的
 * 在 0.4 以下，中间那段几乎是空的；它还得高于 `ROUTE_WEIGHTS.org`，让刚过线的
 * 受控命中仍压过满分的部门命中（rank.test.ts 有断言）。有了真实评估集后按召回 /
 * 先多召回再由重排筛掉。
 */
export const RECALL_MIN = 0.5;
export const RECALL_MAX = 400;
export const RELEVANCE_MIN = 0.55;

/**
 * 排除词否决一段经历的相关度门槛，比正向条件高。
 *
 * 正向条件可以放宽，排除词必须准（AGENTS.md）：召回错了，人在名单上，看一眼
 * 就能纠正；否决错了，证据无声消失，永远没人知道。相关是模糊的，所以否决
 * 只认「几乎就是这个意思」的段。
 */
export const RELEVANCE_MIN_EXCLUDE = 0.75;

/**
 * 时长与近因这两个因子的下限。
 *
 * **它们的乘积必须大于 0.5，这是一条硬约束，不是调参。** 路权重相邻两档之间
 * 最小的比值就是 0.5（org 0.5 : seq 1.0）；只要两个下限的乘积压过 0.5，
 * 同等相关度下一个「干了很久且还在做」的部门命中就能反超一个「刚开始做」的
 * 序列命中——那等于把 ROUTE_WEIGHTS 那套证据强度的论证推翻了。
 *
 * 0.8 × 0.7 = 0.56 > 0.5。所以这两个因子只决定**同一档证据内部**的先后，
 * 永远不会改变档与档之间的顺序。`tests/rank.test.ts` 对此有断言。
 *
 * 相关度**不受**这条保护：一段又长又新、相关 0.7 的序列命中可以反超一段又短
 * 又旧、相关 1.0 的序列命中。这是刻意的——路档位说的是证据可不可信，档与档
 * 之间不许被时长翻盘；相关度只是翻译损耗，不该造出一个不可逾越的档。
 */
export const TENURE_FLOOR = 0.8;
export const RECENCY_FLOOR = 0.7;

/**
 * 累计时长的半饱和点（月）：累计到这个数就拿到时长因子一半的量程。
 *
 * 因子形态是饱和函数 `m / (m + half)`，不是封顶线性 `min(m, cap) / cap`。
 * 封顶线一旦切在人口分布中段，大量长经历会被抹成同一个值；饱和函数处处单调、
 * 恒有界、没有断崖，half 只影响分辨率的疏密。
 *
 * **累计而不是取最长的一段。** 累计才回答「他在这个方向上到底沉淀了多久」。
 * 命中段数因此不单独进分：它已经被累计月数承载了，再乘一次是同一件事数两遍。
 */
export const TENURE_HALF = 48;

/**
 * 近因的半衰点（月）：离开这个方向这么久之后，近因因子衰减到量程的一半。
 *
 * 已经离开这个方向的人与目前仍在做的人对招聘不是一回事；下限不为零，
 * 因为较早的相关经历仍然是有效经历。
 */
export const RECENCY_HALF = 36;

/**
 * 加分词的份量：一个加分词命中时，总分乘以 `1 + 0.5 × 段分`。
 *
 * 上界因此是 1.5 倍。多个加分词会累积并可能改变不同证据档位之间的顺序；这是
 * 「同时满足更多偏好」应有的作用，不受"时长与近因不跨证据档位"那条约束限制。
 * 必须词之间是乘积，一个词弱整个人就被压下去；加分词只会往上抬，不参与准入。
 *
 * 没命中的加分词什么都不乘（不是乘一个小于 1 的数）：那样等于变相把它变成必须词，
 * 而且命中的词越少总分越高——几何平均在缺项时会自己往上飘，这是必须挡住的。
 */
export const BOOST_WEIGHT = 0.5;

/**
 * 一页多少人。「加载更多」每次再要这么多。
 *
 * 50 是一屏扫得完的量级：再多，翻到底之前人就已经忘了前面看过谁。它是**页大小**，
 * 不是结果集的定义——命中多少人由 `total` 说，和这个数无关。
 */
export const RESULT_PAGE = 50;

/**
 * 一次查询最多能翻到多少人。
 *
 * 这是一个诚实的墙，不是一次静默截断：撞到它的时候界面会明说「到上限了，
 * 一共还有 N 人」，而不是让人以为自己已经翻到底。
 *
 * 500 这个数来自载荷而不是审美：每个人带最多 `HITS_PER_TERM × 词数` 条证据，
 * 三个词的查询下 500 人就是四千多个证据对象。再往上，翻页这件事本身
 * 会比重写查询更慢——而在四千人的库里要看超过 500 个候选人，问题出在查询上。
 */
export const RESULT_MAX = 500;

/** 一条条件最多保留几段命中证据用于展示 */
export const HITS_PER_TERM = 3;

/**
 * 「经历时长」这一维**分面的桶**。
 *
 * 它是一种展示：把连续的月数聚成几个数得出人的选项，让筛选能点。
 * 它**不是这一维的值域**——筛选本身接受任意正整数月数（URL 校验、服务端收窄、
 * 查询理解三处同一条口径），模型说「至少 18 个月」照样成立，
 * 而筛选栏会把不在桶里的当前值补进列表（`s/$turnId/-lib/filters.ts` 的 `rows`），
 * 选中态和取消都不受影响。
 */
export const MIN_MONTHS_BUCKETS = [6, 12, 24, 36] as const;

/**
 * 一个词命中超过这个比例的**人**，就判定为**太宽**。
 *
 * 单位是人，不是经历段——这把尺支撑的产品承诺是「几乎筛不掉人」，读数就必须
 * 用同一个单位（论证在 `search.ts` 的 `probeWide`）。载荷那头不归它管：
 * 事实行数由 `FACT_MAX` 保险丝按行兜底，两把尺各管各的单位。
 *
 * 宽不是能预先穷举的词表，是这份语料的事实：「经理」在一家公司命中四成的人，
 * 换一份语料可能只命中百分之三——所以它是一把住在代码里的尺，量的对象问语料。
 * 理解落库时超标的词被**可见地**停用：chip 上只有 `off`，「为什么」是这次理解的
 * 一条注解（`SearchNotice` 的 `wide`）——宽是关于语料的事实，会随语料变化后失效，
 * 而 chips 是记录里不可变的那一半。用户看得见成因，可以换词，也可以坚持启用；
 * 检索层不做无声拦截。查询理解的提示词会把「经理」「运营」这类
 * 功能词挡在前面，这把尺量的是它漏掉的那些。
 *
 * 0.2 的含义：五个人里就有一个命中的词，对「谁该出现在名单上」几乎没有
 * 区分度。这个数只影响「多宽算宽」，不参与任何打分。
 */
export const WIDE_SHARE = 0.2;

/**
 * 一次检索最多把多少行「事实」拉回内存。
 *
 * 这是一根保险丝，不是产品限制：打分与分面都在内存里做（见 rank.ts）。语义
 * 查询的候选行数是 `命中段数 × 条件条数`，纯结构化查询则是一段一行。撞到时
 * 不截断：`overflow` 引导用户具体化经历条件或收窄查询范围；静默截断会让名次、
 * 分面和总数一起说谎。
 */
export const FACT_MAX = 200_000;
