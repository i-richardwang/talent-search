/**
 * 匹配的常数。调参不改查询代码，只改这里。
 *
 * 一条证据说两件事，分开答、不相乘（`rank.ts`）：**可信度**看字段是谁写的，
 * 是三档之一；**深度**看这段原文和查询词多像、做了多久、离开多久，是一个
 * 连续量。可信度是排序的第一把尺，深度是第二把——档与档之间的顺序不会被
 * 深度翻盘，这由排序键的先后保证，不靠任何一个数。
 */

import type { Route } from "#/db/schema";

export type { Route } from "#/db/schema";

/** 证据的可信度，由强到弱。 */
export const STRENGTHS = ["controlled", "org", "claimed"] as const;
export type Strength = (typeof STRENGTHS)[number];

/** 强到弱的序号：排序、SQL 去重、时间轴取最强的一路，比的都是它。 */
export function strengthRank(s: Strength): number {
	return STRENGTHS.indexOf(s);
}

/**
 * 六路证据各有多可信。
 *
 * 序列与岗位是受控字段——HR 系统里为这一段登记的归属，一段一个值、可追溯，
 * 不是本人自述，所以最高。（在职段来自异动流程，入职前段来自工作经历表；
 * 两者都是登记字段，所以同档——强度只看字段来源，不看 kind。）
 *
 * 部门 / 公司同样受控且全员都有，但它描述的是团队的事，不是本人的事，故次之。
 *
 * 自述最低，三条叠加：提到不等于做过；本人自述、无校验；上游文本可能缺失或
 * 被截断。它不该单独把人送进结果，「仅岗位或序列」那个开关挡的就是它。
 *
 * 能力词与做过的事是模型从简历原文里读出来的短说法，**来源**没变，所以和
 * 简历原文同一档：强度只看字段来源，读法再好也不会让自述变成登记。一段经历的
 * 自述证据只有一种读法（`corpus/route-texts.ts`）：读出了说法就只比说法，
 * 没读的段才比整段原文——两者不会同时给同一段作证。
 */
export const ROUTE_STRENGTH: Record<Route, Strength> = {
	seq: "controlled",
	title: "controlled",
	org: "org",
	skill: "claimed",
	did: "claimed",
	description: "claimed",
};

export function isControlledRoute(route: Route) {
	return ROUTE_STRENGTH[route] === "controlled";
}

/** 六路按可信度由强到弱；同档按声明顺序。取数去重和界面枚举共用这一份。 */
export const ROUTE_ORDER = (Object.keys(ROUTE_STRENGTH) as Route[]).sort(
	(a, b) => strengthRank(ROUTE_STRENGTH[a]) - strengthRank(ROUTE_STRENGTH[b]),
);

/**
 * 命中判定分两步，两个模型各管一步（phrases.ts）：
 *
 * 1. **召回**：查询词嵌成向量，取语料里余弦最近的 `RECALL_TOP` 条说法当候选，
 *    再要求过 `RECALL_MIN`。稠密向量在两三个字的短语上区分度很弱（真实语料上
 *    「前端开发」对「后端研发」和对「泛前端研发」都是 0.70，「团队管理」对
 *    「数据管理」0.74），所以这一步只负责**尽量不漏**，下限放得低：真实语料上
 *    不相关的短语落在 0.45 到 0.6，相关说法的余弦最低到 0.51。
 * 2. **判定**：交叉编码器把查询词和每个候选放在一起读，给出相关度；过
 *    `RELEVANCE_MIN` 才算命中。它读的是「说法：释义」（`phrase_gloss`）：光读
 *    四个字它只会数字面重合（「客户开发」对「服务端开发」91%，「前端开发」82%），
 *    跟上一句释义之后对的全在 0.78 以上、错的全在 0.47 以下，这一步于是负责
 *    **不错**。整段简历原文本来就是一段话，不用释义也判得准。
 *
 * `RELEVANCE_MIN` 是整套检索唯一的**成员资格**阈值：AND 判定、总人数、分面
 * 「点了还剩几人」全建立在「过没过这条线」上，所以它必须是一个全站常量，
 * 不能逐查询变。0.55 来自真实语料上的抽样：相关的说法在 0.65 以上，不相关的
 * 在 0.4 以下，中间那段几乎是空的。有了真实评估集后按召回和误召两个读数再调。
 */
export const RECALL_MIN = 0.5;
export const RELEVANCE_MIN = 0.55;

/**
 * 一个词召回多少条说法进重排：按余弦取最近的这么多条。
 *
 * 这是一个明写出来的取舍：**用最后几个百分点的召回，换和语料大小无关的成本。**
 * 「过线的全部」随语料线性涨——语料里说法的种类越多，一个词过 0.5 的越多，
 * 而重排一条约 3 毫秒，一万条就是半分钟；按名次取则永远是这么多条，库再大也
 * 一样。少掉的那几个百分点是粗筛排在名次之外的人：他们的说法确实是这个意思，
 * 只是写法偏门，向量排不到前面。
 *
 * 1000 按人数量过（2026-09-14，四千人、两万九千条说法）：前 1000 名覆盖的人
 * 占「前 3000 名里所有命中的人」的比例，最差的词是「用户增长」90%、「客服」94%，
 * 「算法」「数据分析」100%；前 100 名最差只有三成（「品牌营销」31%）。语料涨了
 * 拿同一把尺重量再定。重排分按词和说法永久缓存，这个数的成本每个词只付一回。
 */
export const RECALL_TOP = 1000;

/**
 * 排除词否决一段经历的相关度门槛，比正向条件高。
 *
 * 正向条件可以放宽，排除词必须准（AGENTS.md）：召回错了，人在名单上，看一眼
 * 就能纠正；否决错了，证据无声消失，永远没人知道。相关是模糊的，所以否决
 * 只认「几乎就是这个意思」的段。
 */
export const RELEVANCE_MIN_EXCLUDE = 0.75;

/**
 * 累计时长的半饱和点（月）：累计到这个数就拿到时长因子一半的量程。
 *
 * 因子形态是饱和函数 `m / (m + half)`，不是封顶线性 `min(m, cap) / cap`。
 * 封顶线一旦切在人口分布中段，大量长经历会被抹成同一个值；饱和函数处处单调、
 * 恒有界、没有断崖，half 只影响分辨率的疏密。
 *
 * **累计而不是取最长的一段。** 累计才回答「他在这个方向上到底沉淀了多久」。
 * 命中段数因此不单独进分：它已经被累计月数承载了，再乘一次是同一件事数两遍。
 *
 * 时长和近因都是深度的因子，量程从零放满：它们只在同一档可信度之内比先后，
 * 档与档之间由排序键隔开（`rank.ts`），所以不需要下限来守住档位。
 */
export const TENURE_HALF = 48;

/**
 * 近因的半衰点（月）：离开这个方向这么久之后，近因因子衰减到量程的一半。
 *
 * 已经离开这个方向的人与目前仍在做的人对招聘不是一回事；因子恒大于零，
 * 因为较早的相关经历仍然是有效经历。
 */
export const RECENCY_HALF = 36;

/**
 * 加分主张的份量：一条加分主张满足时，深度乘以 `1 + 0.5 × 主张的深度`。
 *
 * 上界因此是 1.5 倍。加分只抬深度，不改可信度那一档：档位说的是「必须的那些
 * 主张有多可信」，一条可有可无的主张再硬也不该替它们作证。
 * 必须的主张之间是乘积，一条弱整个人就被压下去；加分的只会往上抬，不参与准入。
 *
 * 没满足的加分条件什么都不乘（不是乘一个小于 1 的数）：那样等于变相把它变成必须，
 * 而且命中的词越少总分越高——几何平均在缺项时会自己往上飘，这是必须挡住的。
 */
export const BOOST_WEIGHT = 0.5;

/**
 * 一页多少人。「加载更多」每次再要这么多。
 *
 * 50 是一屏扫得完的量级：再多，翻到底之前人就已经忘了前面看过谁。它是**页大小**，
 * 不是结果集的定义——命中多少人由 `total` 说，和这个数无关。
 */
export const RESULT_PAGE = 50;

/**
 * 一次查询最多能翻到多少人。
 *
 * 这是一个诚实的墙，不是一次静默截断：撞到它的时候界面会明说「到上限了，
 * 一共还有 N 人」，而不是让人以为自己已经翻到底。
 *
 * 500 这个数来自载荷而不是审美：每个人带最多 `HITS_PER_CLAIM × 主张数` 条证据，
 * 三条主张的查询下 500 人就是四千多个证据对象。再往上，翻页这件事本身
 * 会比重写查询更慢——而在四千人的库里要看超过 500 个候选人，问题出在查询上。
 */
export const RESULT_MAX = 500;

/** 一条主张最多保留几段命中证据用于展示 */
export const HITS_PER_CLAIM = 3;

/**
 * 「经历时长」这一维**分面的桶**。
 *
 * 它是一种展示：把连续的月数聚成几个数得出人的选项，让筛选能点。
 * 它**不是这一维的值域**——筛选本身接受任意正整数月数（URL 与 RPC 两处都走
 * `DIMENSIONS.minMonths.parse`），手拼「至少 18 个月」照样成立，
 * 而筛选栏会把不在桶里的当前值补进列表（`s/$turnId/-lib/filters.ts` 的 `rows`），
 * 选中态和取消都不受影响。
 */
export const MIN_MONTHS_BUCKETS = [6, 12, 24, 36] as const;

/**
 * 一个词命中超过这个比例的**人**，就判定为**太宽**。
 *
 * 单位是人，不是经历段——这把尺支撑的产品承诺是「几乎筛不掉人」，读数就必须
 * 用同一个单位（论证在 `search.ts` 的 `probeWide`）。载荷那头不归它管：
 * 事实行数由 `FACT_MAX` 保险丝按行兜底，两把尺各管各的单位。
 *
 * 宽不是能预先穷举的词表，是这份语料的事实：「经理」在一家公司命中四成的人，
 * 换一份语料可能只命中百分之三——所以它是一把住在代码里的尺，量的对象问语料。
 * 理解落库时超标的词被**可见地**停用：chip 上只有 `off`，「为什么」是这次理解的
 * 一条注解（`SearchNotice` 的 `wide`）——宽是关于语料的事实，会随语料变化后失效，
 * 而 chips 是记录里不可变的那一半。用户看得见成因，可以换词，也可以坚持启用；
 * 检索层不做无声拦截。查询理解的提示词会把「经理」「运营」这类
 * 功能词挡在前面，这把尺量的是它漏掉的那些。
 *
 * 0.2 的含义：五个人里就有一个命中的词，对「谁该出现在名单上」几乎没有
 * 区分度。这个数只影响「多宽算宽」，不参与任何打分。
 */
export const WIDE_SHARE = 0.2;

/**
 * 一次检索最多把多少行「事实」拉回内存。
 *
 * 这是一根保险丝，不是产品限制：打分与分面都在内存里做（见 rank.ts）。有经历词的
 * 主张一条命中段一行，没有经历词的主张落在范围里的每一段一行，只有人的条件时
 * 一段一行。撞到时不截断：`overflow` 引导用户具体化经历词或再加一项条件；
 * 静默截断会让名次、分面和总数一起说谎。
 */
export const FACT_MAX = 200_000;
